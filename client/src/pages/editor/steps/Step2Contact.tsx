import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Badge } from "@/components/ui/badge";
import { Sparkles, Mail, MapPin, MessageSquare, Copyright, Check, Info } from "lucide-react";
import type { StepProps } from "../types";
import { useEffect } from "react";

export default function Step2Contact({ data, setData }: StepProps) {
    const isLocationAutoFilled = data.contact.location === data.about.personal.location && data.about.personal.location;
    const isCopyrightAutoGenerated = data.contact.copyright && data.about.personal.name;

    // Auto-fill location from Step 1
    useEffect(() => {
        if (data.about.personal.location && !data.contact.location) {
            setData((prev) => ({
                ...prev,
                contact: { ...prev.contact, location: data.about.personal.location },
            }));
        }
    }, [data.about.personal.location, data.contact.location, setData]);

    const completionPercentage = () => {
        let completed = 0;
        if (data.contact.email) completed += 40;
        if (data.contact.location) completed += 30;
        if (data.contact.message) completed += 15;
        if (data.contact.copyright) completed += 15;
        return completed;
    };

    return (
        <div className="max-w-[1400px] mx-auto">
            {/* Header Section */}
            <div className="mb-10">
                <div className="flex items-start justify-between">
                    <div>
                        <h2 className="text-4xl font-bold text-foreground mb-2">Contact Information</h2>
                        <p className="text-muted-foreground text-lg">Let people know how to reach you</p>
                    </div>
                    <div className="flex items-center gap-3 bg-gradient-to-r from-primary/10 to-purple-500/10 px-6 py-4 rounded-2xl border border-primary/30">
                        <div className="text-right">
                            <div className="text-xs text-muted-foreground uppercase tracking-wide font-medium">Completion</div>
                            <div className="text-2xl font-bold bg-gradient-to-r from-blue-600 to-purple-600 bg-clip-text text-transparent">
                                {completionPercentage()}%
                            </div>
                        </div>
                        <Sparkles className="w-6 h-6 text-purple-500" />
                    </div>
                </div>
            </div>

            {/* Auto-fill Notice */}
            {(isLocationAutoFilled || isCopyrightAutoGenerated) && (
                <div className="mb-8 p-6 bg-gradient-to-r from-primary/10 via-purple-500/10 to-primary/10 border-2 border-primary/30 rounded-2xl flex items-start gap-4 shadow-sm">
                    <div className="w-10 h-10 rounded-xl bg-primary/100 flex items-center justify-center flex-shrink-0">
                        <Sparkles className="w-5 h-5 text-white" />
                    </div>
                    <div>
                        <p className="text-base font-bold text-primary">Smart Auto-Fill Active ✨</p>
                        <p className="text-sm text-primary mt-1">
                            Some fields are automatically filled from your personal info. You can edit them anytime.
                        </p>
                    </div>
                </div>
            )}

            {/* Main Grid Layout */}
            <div className="grid grid-cols-[1fr_380px] gap-8">
                {/* Left Column - Form Fields */}
                <div className="space-y-6">
                    {/* Email Card */}
                    <div className="bg-card rounded-2xl p-8 border-2 border shadow-md">
                        <div className="flex items-center gap-3 mb-6">
                            <div className="w-10 h-10 rounded-xl bg-blue-100 flex items-center justify-center">
                                <Mail className="w-5 h-5 text-blue-600" />
                            </div>
                            <div>
                                <h3 className="text-xl font-bold text-foreground">Email Address</h3>
                                <p className="text-sm text-muted-foreground">Primary contact method</p>
                            </div>
                        </div>
                        <div className="space-y-2">
                            <Label htmlFor="email" className="text-sm font-semibold text-foreground flex items-center gap-2">
                                <Mail className="w-4 h-4" />
                                Email *
                            </Label>
                            <Input
                                id="email"
                                type="email"
                                value={data.contact.email}
                                onChange={(e) =>
                                    setData((prev) => ({
                                        ...prev,
                                        contact: { ...prev.contact, email: e.target.value },
                                    }))
                                }
                                placeholder="your.email@example.com"
                                className="h-12 text-base"
                            />
                            <div className="flex items-start gap-2 mt-2">
                                <Info className="w-4 h-4 text-gray-400 mt-0.5 flex-shrink-0" />
                                <p className="text-xs text-muted-foreground">This will be used for contact forms and displayed on your portfolio</p>
                            </div>
                        </div>
                    </div>

                    {/* Location Card */}
                    <div className="bg-card rounded-2xl p-8 border-2 border shadow-md">
                        <div className="flex items-center gap-3 mb-6">
                            <div className="w-10 h-10 rounded-xl bg-green-100 flex items-center justify-center">
                                <MapPin className="w-5 h-5 text-green-600" />
                            </div>
                            <div className="flex-1">
                                <h3 className="text-xl font-bold text-foreground">Location</h3>
                                <p className="text-sm text-muted-foreground">Where you're based</p>
                            </div>
                            {isLocationAutoFilled && (
                                <Badge variant="secondary" className="text-xs gap-1 px-3 py-1">
                                    <Sparkles className="w-3 h-3" />
                                    Auto-filled
                                </Badge>
                            )}
                        </div>
                        <div className="space-y-2">
                            <Label htmlFor="contact-location" className="text-sm font-semibold text-foreground flex items-center gap-2">
                                <MapPin className="w-4 h-4" />
                                Location *
                            </Label>
                            <Input
                                id="contact-location"
                                value={data.contact.location}
                                onChange={(e) =>
                                    setData((prev) => ({
                                        ...prev,
                                        contact: { ...prev.contact, location: e.target.value },
                                    }))
                                }
                                placeholder="San Francisco, CA"
                                className="h-12 text-base"
                            />
                            <div className="flex items-start gap-2 mt-2">
                                <Info className="w-4 h-4 text-gray-400 mt-0.5 flex-shrink-0" />
                                <p className="text-xs text-muted-foreground">Your current city and country</p>
                            </div>
                        </div>
                    </div>

                    {/* Welcome Message Card */}
                    <div className="bg-card rounded-2xl p-8 border-2 border shadow-md">
                        <div className="flex items-center gap-3 mb-6">
                            <div className="w-10 h-10 rounded-xl bg-purple-100 flex items-center justify-center">
                                <MessageSquare className="w-5 h-5 text-purple-600" />
                            </div>
                            <div>
                                <h3 className="text-xl font-bold text-foreground">Welcome Message</h3>
                                <p className="text-sm text-muted-foreground">
                                    Optional - Greet your visitors
                                    <span className="text-xs text-gray-400 ml-1">(Optional)</span>
                                </p>
                            </div>
                        </div>
                        <div className="space-y-2">
                            <Label htmlFor="message" className="text-sm font-semibold text-foreground flex items-center gap-2">
                                <MessageSquare className="w-4 h-4" />
                                Message
                                <span className="text-xs text-muted-foreground font-normal">(Optional)</span>
                            </Label>
                            <Textarea
                                id="message"
                                value={data.contact.message}
                                onChange={(e) =>
                                    setData((prev) => ({
                                        ...prev,
                                        contact: { ...prev.contact, message: e.target.value },
                                    }))
                                }
                                placeholder="Let's work together on your next project..."
                                rows={5}
                                className="resize-none text-base"
                            />
                            <div className="flex justify-between items-center">
                                <div className="flex items-start gap-2">
                                    <Info className="w-4 h-4 text-gray-400 mt-0.5 flex-shrink-0" />
                                    <p className="text-xs text-muted-foreground">A friendly message for visitors on your contact page</p>
                                </div>
                                <p className="text-xs text-gray-400">{data.contact.message.length} characters</p>
                            </div>
                        </div>
                    </div>

                    {/* Copyright Card */}
                    <div className="bg-card rounded-2xl p-8 border-2 border shadow-md">
                        <div className="flex items-center gap-3 mb-6">
                            <div className="w-10 h-10 rounded-xl bg-orange-100 flex items-center justify-center">
                                <Copyright className="w-5 h-5 text-orange-600" />
                            </div>
                            <div className="flex-1">
                                <h3 className="text-xl font-bold text-foreground">Copyright Text</h3>
                                <p className="text-sm text-muted-foreground">Footer legal notice</p>
                            </div>
                            {isCopyrightAutoGenerated && (
                                <Badge variant="secondary" className="text-xs gap-1 px-3 py-1">
                                    <Sparkles className="w-3 h-3" />
                                    Auto-generated
                                </Badge>
                            )}
                        </div>
                        <div className="space-y-2">
                            <Label htmlFor="copyright" className="text-sm font-semibold text-foreground flex items-center gap-2">
                                <Copyright className="w-4 h-4" />
                                Copyright
                                <span className="text-xs text-muted-foreground font-normal">(Optional)</span>
                            </Label>
                            <Input
                                id="copyright"
                                value={data.contact.copyright}
                                onChange={(e) =>
                                    setData((prev) => ({
                                        ...prev,
                                        contact: { ...prev.contact, copyright: e.target.value },
                                    }))
                                }
                                placeholder="© 2024 Your Name. All rights reserved."
                                className="h-12 text-base"
                            />
                            <div className="flex items-start gap-2 mt-2">
                                <Info className="w-4 h-4 text-gray-400 mt-0.5 flex-shrink-0" />
                                <p className="text-xs text-muted-foreground">Displayed in the footer of your portfolio</p>
                            </div>
                        </div>
                    </div>
                </div>

                {/* Right Column - Preview & Checklist */}
                <div className="space-y-6">
                    {/* Checklist Card */}
                    <div className="bg-card rounded-2xl p-6 border-2 border shadow-md">
                        <div className="flex items-center gap-2 mb-5">
                            <Check className="w-5 h-5 text-blue-600" />
                            <h4 className="font-bold text-foreground">Contact Checklist</h4>
                        </div>
                        <div className="space-y-3">
                            {[
                                { label: "Email Address", value: data.contact.email, icon: Mail, required: true },
                                { label: "Location", value: data.contact.location, icon: MapPin, required: true },
                                { label: "Welcome Message", value: data.contact.message, icon: MessageSquare, required: false },
                                { label: "Copyright Text", value: data.contact.copyright, icon: Copyright, required: false },
                            ].map((item, idx) => {
                                const Icon = item.icon;
                                const isComplete = !!item.value;
                                return (
                                    <div
                                        key={idx}
                                        className={`flex items-center justify-between p-3 rounded-xl transition-all ${isComplete ? "bg-green-50 border border-green-200" : "bg-muted border border"
                                            }`}
                                    >
                                        <div className="flex items-center gap-3">
                                            <Icon className={`w-4 h-4 ${isComplete ? "text-green-600" : "text-gray-400"}`} />
                                            <span className={`text-sm font-medium ${isComplete ? "text-green-900" : "text-muted-foreground"}`}>
                                                {item.label}
                                                {!item.required && <span className="text-xs text-gray-400 ml-1">(Optional)</span>}
                                            </span>
                                        </div>
                                        {isComplete ? (
                                            <Check className="w-5 h-5 text-green-600" />
                                        ) : (
                                            <div className="w-5 h-5 rounded-full border-2 border" />
                                        )}
                                    </div>
                                );
                            })}
                        </div>
                    </div>

                    {/* Preview Card */}
                    <div className="bg-gradient-to-br from-muted/30 to-muted/50 rounded-2xl p-6 border-2 border shadow-md">
                        <div className="flex items-center gap-2 mb-5">
                            <div className="w-8 h-8 rounded-lg bg-gradient-to-r from-blue-600 to-purple-600 flex items-center justify-center">
                                <Sparkles className="w-4 h-4 text-white" />
                            </div>
                            <h4 className="font-bold text-foreground">Live Preview</h4>
                        </div>
                        <div className="space-y-4">
                            <div className="bg-card rounded-xl p-4 border border">
                                <div className="flex items-start gap-3">
                                    <Mail className="w-5 h-5 text-blue-600 mt-0.5" />
                                    <div className="flex-1">
                                        <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wide">Email</span>
                                        <p className="text-sm text-foreground mt-1 font-medium break-all">
                                            {data.contact.email || <span className="text-gray-400 italic">Not set</span>}
                                        </p>
                                    </div>
                                </div>
                            </div>
                            <div className="bg-card rounded-xl p-4 border border">
                                <div className="flex items-start gap-3">
                                    <MapPin className="w-5 h-5 text-green-600 mt-0.5" />
                                    <div className="flex-1">
                                        <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wide">Location</span>
                                        <p className="text-sm text-foreground mt-1 font-medium">
                                            {data.contact.location || <span className="text-gray-400 italic">Not set</span>}
                                        </p>
                                    </div>
                                </div>
                            </div>
                            <div className="bg-card rounded-xl p-4 border border">
                                <div className="flex items-start gap-3">
                                    <MessageSquare className="w-5 h-5 text-purple-600 mt-0.5" />
                                    <div className="flex-1">
                                        <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wide">Message</span>
                                        <p className="text-sm text-foreground mt-1">
                                            {data.contact.message || <span className="text-gray-400 italic">Not set</span>}
                                        </p>
                                    </div>
                                </div>
                            </div>
                            <div className="bg-card rounded-xl p-4 border border">
                                <div className="flex items-start gap-3">
                                    <Copyright className="w-5 h-5 text-orange-600 mt-0.5" />
                                    <div className="flex-1">
                                        <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wide">Copyright</span>
                                        <p className="text-sm text-foreground mt-1">
                                            {data.contact.copyright || <span className="text-gray-400 italic">Not set</span>}
                                        </p>
                                    </div>
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
            </div>
        </div>
    );
}



