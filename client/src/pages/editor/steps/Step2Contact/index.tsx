import { Sparkles } from "lucide-react";
import { useEffect, useState } from "react";
import type { StepProps } from "../../types";
import { saveContactData } from "@/lib/firebase-service";
import { useToast } from "@/hooks/use-toast";
import EmailField from "./EmailField";
import LocationField from "./LocationField";
import WelcomeMessage from "./WelcomeMessage";
import CopyrightField from "./CopyrightField";
import ContactChecklist from "./ContactChecklist";
import LivePreview from "./LivePreview";
import { calculateStep2Completion } from "../../lib/completionCalculator";

export default function Step2Contact({ data, setData }: StepProps) {
    const [savingField, setSavingField] = useState<string | null>(null);
    const { toast } = useToast();
    const isLocationAutoFilled = !!(data.contact.location === data.about.personal.location && data.about.personal.location);
    const isCopyrightAutoGenerated = !!(data.contact.copyright && data.about.personal.name);

    // Save individual field to Firebase
    const saveField = async (fieldName: string) => {
        try {
            setSavingField(fieldName);
            await saveContactData(data.contact);
            toast({
                title: "Saved!",
                description: `${fieldName} has been saved to Firebase`,
            });
        } catch (error) {
            console.error("Save error:", error);
            toast({
                title: "Save Failed",
                description: "Could not save to Firebase. Please try again.",
                variant: "destructive",
            });
        } finally {
            setSavingField(null);
        }
    };

    // Auto-fill location from Step 1
    useEffect(() => {
        if (data.about.personal.location && !data.contact.location) {
            setData((prev) => ({
                ...prev,
                contact: { ...prev.contact, location: data.about.personal.location },
            }));
        }
    }, [data.about.personal.location, data.contact.location, setData]);

    const handleEmailChange = (value: string) => {
        setData((prev) => ({
            ...prev,
            contact: { ...prev.contact, email: value },
        }));
    };

    const handleLocationChange = (value: string) => {
        setData((prev) => ({
            ...prev,
            contact: { ...prev.contact, location: value },
        }));
    };

    const handleMessageChange = (value: string) => {
        setData((prev) => ({
            ...prev,
            contact: { ...prev.contact, message: value },
        }));
    };

    const handleCopyrightChange = (value: string) => {
        setData((prev) => ({
            ...prev,
            contact: { ...prev.contact, copyright: value },
        }));
    };

    return (
        <div className="max-w-[1400px] mx-auto">
            {/* Header Section */}
            <div className="mb-10">
                <div className="flex items-start justify-between">
                    <div>
                        <h2 className="text-4xl font-bold text-foreground mb-2">Contact Information</h2>
                        <p className="text-muted-foreground text-lg">Let people know how to reach you</p>
                    </div>
                    <div className="flex items-center gap-3 bg-card px-6 py-4 rounded-2xl border-2 border">
                        <div className="text-right">
                            <div className="text-xs text-muted-foreground uppercase tracking-wide font-medium">Completion</div>
                            <div className="text-2xl font-bold text-primary">
                                {calculateStep2Completion(data)}%
                            </div>
                        </div>
                        <Sparkles className="w-6 h-6 text-primary" />
                    </div>
                </div>
            </div>

            {/* Auto-fill Notice */}
            {(isLocationAutoFilled || isCopyrightAutoGenerated) && (
                <div className="mb-8 p-6 bg-card border-2 border-primary rounded-2xl flex items-start gap-4 shadow-sm">
                    <div className="w-10 h-10 rounded-xl bg-primary flex items-center justify-center flex-shrink-0">
                        <Sparkles className="w-5 h-5 text-primary-foreground" />
                    </div>
                    <div>
                        <p className="text-base font-bold text-foreground">Smart Auto-Fill Active ✨</p>
                        <p className="text-sm text-muted-foreground mt-1">
                            Some fields are automatically filled from your personal info. You can edit them anytime.
                        </p>
                    </div>
                </div>
            )}

            {/* Main Grid Layout */}
            <div className="grid grid-cols-[1fr_380px] gap-8">
                {/* Left Column - Form Fields */}
                <div className="space-y-6">
                    <EmailField
                        email={data.contact.email}
                        onEmailChange={handleEmailChange}
                        onSave={saveField}
                        savingField={savingField}
                    />
                    <LocationField
                        location={data.contact.location}
                        onLocationChange={handleLocationChange}
                        onSave={saveField}
                        savingField={savingField}
                        isAutoFilled={isLocationAutoFilled}
                    />
                    <WelcomeMessage
                        message={data.contact.message}
                        onMessageChange={handleMessageChange}
                    />
                    <CopyrightField
                        copyright={data.contact.copyright}
                        onCopyrightChange={handleCopyrightChange}
                        isAutoGenerated={isCopyrightAutoGenerated}
                    />
                </div>

                {/* Right Column - Preview & Checklist */}
                <div className="space-y-6">
                    <ContactChecklist data={data} />
                    <LivePreview data={data} />
                </div>
            </div>
        </div>
    );
}
