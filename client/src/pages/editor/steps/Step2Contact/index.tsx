import { useEffect, useState } from "react";
import type { StepProps } from "../../types";
import { saveContactData } from "@/lib/firebase-service";
import { useToast } from "@/hooks/use-toast";
import { Mail, MapPin, MessageSquare, Copyright, Save, Loader2, Check } from "lucide-react";

export default function Step2Contact({ data, setData }: StepProps) {
  const [savingField, setSavingField] = useState<string | null>(null);
  const { toast } = useToast();
  const isLocationAutoFilled = !!(data.contact.location === data.about.personal.location && data.about.personal.location);
  const isCopyrightAutoGenerated = !!(data.contact.copyright && data.about.personal.name);

  const saveField = async (fieldName: string) => {
    try {
      setSavingField(fieldName);
      await saveContactData(data.contact);
      toast({ title: "Saved!", description: `${fieldName} has been saved to Firebase` });
    } catch (error) {
      console.error("Save error:", error);
      toast({ title: "Save Failed", description: "Could not save to Firebase.", variant: "destructive" });
    } finally {
      setSavingField(null);
    }
  };

  useEffect(() => {
    if (data.about.personal.location && !data.contact.location) {
      setData((prev) => ({
        ...prev,
        contact: { ...prev.contact, location: data.about.personal.location },
      }));
    }
  }, [data.about.personal.location, data.contact.location, setData]);

  const update = (field: string, value: string) => {
    setData((prev) => ({ ...prev, contact: { ...prev.contact, [field]: value } }));
  };

  const fields = [
    { key: "email", label: "Email Address", icon: Mail, value: data.contact.email, type: "email", placeholder: "your.email@example.com", required: true },
    { key: "location", label: "Location", icon: MapPin, value: data.contact.location, type: "text", placeholder: "Sikar, Rajasthan, India", required: true, badge: isLocationAutoFilled ? "Auto-filled" : null },
    { key: "message", label: "Welcome Message", icon: MessageSquare, value: data.contact.message, type: "textarea", placeholder: "Hi, I'm Anni — let's build something great together!", required: false },
    { key: "copyright", label: "Copyright Text", icon: Copyright, value: data.contact.copyright, type: "text", placeholder: "© 2025 Your Name. All rights reserved.", required: false, badge: isCopyrightAutoGenerated ? "Auto-generated" : null },
  ];

  const completed = fields.filter(f => f.required ? !!f.value : false).length;
  const requiredCount = fields.filter(f => f.required).length;

  return (
    <div>
      {/* Header */}
      <div style={{ marginBottom: 20, display: "flex", alignItems: "center", justifyContent: "space-between", flexWrap: "wrap", gap: 12 }}>
        <div>
          <h2 style={{ fontSize: 22, fontWeight: 800, color: "var(--ed-text)", letterSpacing: "-0.02em" }}>Contact Information</h2>
          <p style={{ fontSize: 13, color: "var(--ed-text-secondary)", marginTop: 2 }}>Let people know how to reach you</p>
        </div>
        <div style={{ display: "flex", alignItems: "center", gap: 8, padding: "8px 16px", background: "var(--ed-surface)", borderRadius: "var(--ed-radius-sm)", border: "1px solid var(--ed-border)" }}>
          <Check style={{ width: 16, height: 16, color: "var(--ed-success)" }} />
          <span style={{ fontSize: 13, fontWeight: 700, color: "var(--ed-text)" }}>{completed}/{requiredCount}</span>
          <span style={{ fontSize: 11, color: "var(--ed-text-muted)" }}>required</span>
        </div>
      </div>

      {/* Single Card — All Fields */}
      <div className="editor-card" style={{ marginBottom: 16 }}>
        <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
          {fields.map((f) => {
            const Icon = f.icon;
            const isTextarea = f.type === "textarea";
            return (
              <div key={f.key}>
                <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: 6 }}>
                  <label className="editor-label" style={{ marginBottom: 0 }}>
                    <Icon /> {f.label}
                    {!f.required && <span style={{ fontSize: 10, opacity: 0.5 }}>(Optional)</span>}
                  </label>
                  <div style={{ display: "flex", alignItems: "center", gap: 6 }}>
                    {f.badge && (
                      <span style={{ fontSize: 10, fontWeight: 600, color: "var(--ed-primary)", background: "var(--ed-primary-glow)", padding: "2px 8px", borderRadius: 20 }}>
                        ✦ {f.badge}
                      </span>
                    )}
                    <button onClick={() => saveField(f.label)} disabled={savingField === f.label || (!f.required && !f.value)} className="editor-btn-icon" style={{ width: 32, height: 32 }}>
                      {savingField === f.label ? <Loader2 className="w-3 h-3 animate-spin" /> : <Save className="w-3 h-3" />}
                    </button>
                  </div>
                </div>
                {isTextarea ? (
                  <textarea
                    value={f.value}
                    onChange={(e) => update(f.key, e.target.value)}
                    placeholder={f.placeholder}
                    rows={3}
                    className="editor-input resize-none"
                  />
                ) : (
                  <input
                    type={f.type}
                    value={f.value}
                    onChange={(e) => update(f.key, e.target.value)}
                    placeholder={f.placeholder}
                    className="editor-input"
                  />
                )}
              </div>
            );
          })}
        </div>
      </div>

      {/* Preview */}
      <div className="editor-card">
        <div className="editor-card-header" style={{ marginBottom: 12 }}>
          <div className="editor-card-icon"><Mail /></div>
          <h3 style={{ fontSize: 14, fontWeight: 700, color: "var(--ed-text)" }}>Preview</h3>
        </div>
        <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10 }}>
          {[
            { icon: Mail, label: "Email", value: data.contact.email },
            { icon: MapPin, label: "Location", value: data.contact.location },
            { icon: MessageSquare, label: "Message", value: data.contact.message },
            { icon: Copyright, label: "Copyright", value: data.contact.copyright },
          ].map((p) => {
            const PIcon = p.icon;
            return (
              <div key={p.label} style={{ padding: "10px 12px", background: "var(--ed-surface-2)", borderRadius: "var(--ed-radius-xs)", border: "1px solid var(--ed-border)" }}>
                <div style={{ display: "flex", alignItems: "center", gap: 6, marginBottom: 4 }}>
                  <PIcon style={{ width: 12, height: 12, color: "var(--ed-text-muted)" }} />
                  <span style={{ fontSize: 10, fontWeight: 700, textTransform: "uppercase", letterSpacing: "0.05em", color: "var(--ed-text-muted)" }}>{p.label}</span>
                </div>
                <p style={{ fontSize: 12, color: "var(--ed-text)", fontWeight: 500, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                  {p.value || <span style={{ color: "var(--ed-text-muted)", fontStyle: "italic" }}>Not set</span>}
                </p>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}
